# Camera Automation Windows Build Script
# This script builds the production package using PyInstaller

param (
    [string]$BuildType = "onedir",  # "onedir" or "onefile"
    [string]$OutputDir = "dist",
    [bool]$CleanBuild = $true,
    [bool]$IncludeDebugSymbols = $false
)

# Configuration
$ProjectName = "CameraAutomation"
$MainScript = "camera_service/launcher.py"
$IconPath = "camera_service/web/favicon.ico"  # Create this if needed
$SpecFile = "packaging/windows/CameraAutomation.spec"
$PythonPath = "python"
$PyInstallerPath = "pyinstaller"

# Ensure we're in the project root
$ProjectRoot = $PSScriptRoot + "\..\.."
Set-Location $ProjectRoot

# Clean previous build if requested
if ($CleanBuild) {
    Write-Host "Cleaning previous build..."
    if (Test-Path "$OutputDir") {
        Remove-Item "$OutputDir" -Recurse -Force
    }
    if (Test-Path "build") {
        Remove-Item "build" -Recurse -Force
    }
}

# Create output directory
if (-not (Test-Path "$OutputDir")) {
    New-Item -ItemType Directory -Path "$OutputDir" | Out-Null
}

# Check if PyInstaller is available
try {
    & $PythonPath -m pip show pyinstaller | Out-Null
} catch {
    Write-Host "PyInstaller not found. Installing..."
    & $PythonPath -m pip install pyinstaller
}

# Create or update the spec file
$SpecContent = @"
