"@

# Write the spec file
$SpecContent | Out-File -FilePath $SpecFile -Encoding utf8

# Build the application
Write-Host "Building Camera Automation ($BuildType mode)..."

$BuildArgs = @(
    "--$BuildType",
    "--name", "$ProjectName",
    "--distpath", "$OutputDir",
    "--workpath", "build",
    "--specpath", "packaging/windows",
    "--clean"
)

if ($IncludeDebugSymbols) {
    $BuildArgs += "--debug=all"
}

if (Test-Path $IconPath) {
    $BuildArgs += "--icon", "$IconPath"
}

try {
    Write-Host "Running PyInstaller..."
    & $PyInstallerPath @BuildArgs $SpecFile

    Write-Host "Build completed successfully!"
    Write-Host "Output directory: $OutputDir"

    # Check if the build was successful
    $ExpectedPath = Join-Path $OutputDir $ProjectName
    if ($BuildType -eq "onedir") {
        $ExpectedPath = Join-Path $ExpectedPath "$ProjectName.exe"
    } else {
        $ExpectedPath = Join-Path $ExpectedPath ".exe"
    }

    if (Test-Path $ExpectedPath) {
        Write-Host "Build successful! Executable created at: $ExpectedPath"
    } else {
        Write-Host "Build may have failed. Expected executable not found at: $ExpectedPath"
    }
} catch {
    Write-Host "Build failed with error: $_"
    exit 1
}

# Create start/stop scripts
$StartScriptContent = @"
@echo off
SETLOCAL

REM Camera Automation Start Script
REM This script starts the Camera Automation application

SET APP_DIR=%~dp0
SET APP_NAME=CameraAutomation.exe

echo Starting Camera Automation...
echo Application Directory: %APP_DIR%

cd /d "%APP_DIR%"

if exist "%APP_NAME%" (
    start "" "%APP_NAME%"
    echo Camera Automation started successfully.
    echo Opening browser to setup page...
    timeout /t 2 /nobreak >nul
    start "" "http://127.0.0.1:8000/setup"
) else (
    echo Error: %APP_NAME% not found in %APP_DIR%
    pause
)

ENDLOCAL
"@

$StopScriptContent = @"
@echo off
SETLOCAL

REM Camera Automation Stop Script
REM This script stops the Camera Automation application

echo Stopping Camera Automation...

taskkill /f /im CameraAutomation.exe >nul 2>&1
taskkill /f /im python.exe >nul 2>&1

echo Camera Automation stopped.
pause

ENDLOCAL
"@

# Write start/stop scripts
$StartScriptContent | Out-File -FilePath "START_CAMERA_AUTOMATION.bat" -Encoding utf8
$StopScriptContent | Out-File -FilePath "STOP_CAMERA_AUTOMATION.bat" -Encoding utf8

Write-Host "Created START_CAMERA_AUTOMATION.bat and STOP_CAMERA_AUTOMATION.bat"

